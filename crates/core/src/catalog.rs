pub fn service_profile(port: u16, transport: &str) -> Option<&'static ServiceProfile> {
    let needle = transport.to_ascii_lowercase();
    SERVICE_PROFILES.iter().find(|profile| profile.port == port && (profile.transport == needle || profile.transport == "tcp-udp"))
}
pub fn port_exposure_score(port: u16, transport: &str) -> u8 {
    service_profile(port, transport).map(|p| p.exposure).unwrap_or_else(|| if port < 1024 { 35 } else if port >= 49152 { 10 } else { 20 })
}
pub fn protocol_name(number: u8) -> &'static str {
    match number {
        1 => "icmp",
        2 => "igmp",
        6 => "tcp",
        17 => "udp",
        41 => "ipv6",
        47 => "gre",
        50 => "esp",
        51 => "ah",
        58 => "icmpv6",
        89 => "ospf",
        132 => "sctp",
        _ => "unknown",
    }
}
pub fn dns_record_name(rrtype: u16) -> &'static str {
    match rrtype {
        1 => "A",
        2 => "NS",
        5 => "CNAME",
        6 => "SOA",
        12 => "PTR",
        15 => "MX",
        16 => "TXT",
        28 => "AAAA",
        33 => "SRV",
        43 => "DS",
        46 => "RRSIG",
        47 => "NSEC",
        48 => "DNSKEY",
        52 => "TLSA",
        65 => "HTTPS",
        255 => "ANY",
        _ => "UNKNOWN",
    }
}
pub fn suspicious_url_token(token: &str) -> bool {
    matches!(token, "admin" | "cmd" | "shell" | "powershell" | "download" | "payload" | "beacon" | "gate" | "panel" | "login" | "wp-admin" | "cgi-bin" | "eval" | "base64" | "token" | "key" | "secret" | "backup" | "dump" | "config" | "passwd")
}
